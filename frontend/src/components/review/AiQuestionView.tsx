/**
 * The AI-question part of the review card, shared by the review page and the admin Questions page
 * so the admin sees exactly what a learner sees.
 */

/** The label the review card shows above an AI question. */
export const AI_QUESTION_LABEL = "Usage patterns";

export function AiBadge() {
  return (
    <span
      className="px-2 py-0.5 text-[10px] font-bold uppercase tracking-wide bg-purple-700/70 text-purple-100 rounded-full shrink-0"
      title="This question was generated by AI — if it seems off, you can flag it after answering."
    >
      AI
    </span>
  );
}

/** The optional italic context line, then the question. */
export function AiQuestionBody({ context, question }: { context?: string | null; question: string | null }) {
  return (
    <>
      {context && <p className="text-xl text-gray-300 mb-4 italic">{context}</p>}
      <p className="text-2xl font-bold text-white break-words">{question || "[Question not loaded]"}</p>
    </>
  );
}

/** The whole question area of an AI-question review card: label, badge, context and question. */
export default function AiQuestionView({ context, question }: { context?: string | null; question: string }) {
  return (
    <div className="text-center flex flex-col justify-center">
      <p className="text-lg font-semibold text-blue-300 mb-3 truncate px-4 flex items-center justify-center gap-2">
        <span>{AI_QUESTION_LABEL}</span>
        <AiBadge />
      </p>
      <AiQuestionBody context={context} question={question} />
    </div>
  );
}
